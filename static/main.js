const root = document.documentElement;
const menuToggle = document.querySelector("[data-menu-toggle]");
const headerPanel = document.querySelector("[data-header-panel]");
const languageButtons = document.querySelectorAll("[data-language]");
const currentYear = document.querySelector("[data-current-year]");
const description = document.querySelector('meta[name="description"]');
const openGraphTitle = document.querySelector('meta[property="og:title"]');
const openGraphDescription = document.querySelector('meta[property="og:description"]');
const openGraphLocale = document.querySelector('meta[property="og:locale"]');

let currentLanguage = "ar";

function storedLanguage() {
  try {
    const value = window.localStorage.getItem("preferred-language");
    return value === "en" || value === "ar" ? value : "ar";
  } catch {
    return "ar";
  }
}

function storeLanguage(language) {
  try {
    window.localStorage.setItem("preferred-language", language);
  } catch {
    // The language still works when private browsing blocks local storage.
  }
}

function updateMenuLabel(isOpen) {
  if (!menuToggle) return;
  const dictionary = translations[currentLanguage];
  menuToggle.setAttribute("aria-label", isOpen ? dictionary.closeMenu : dictionary.openMenu);
}

function setMenu(isOpen) {
  if (!menuToggle || !headerPanel) return;
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  headerPanel.classList.toggle("is-open", isOpen);
  updateMenuLabel(isOpen);
}

function applyLanguage(language, persist = true) {
  const selectedLanguage = translations[language] ? language : "ar";
  const dictionary = translations[selectedLanguage];
  currentLanguage = selectedLanguage;

  root.lang = selectedLanguage;
  root.dir = selectedLanguage === "ar" ? "rtl" : "ltr";
  document.title = dictionary.metaTitle;

  if (description) description.content = dictionary.metaDescription;
  if (openGraphTitle) openGraphTitle.content = dictionary.metaTitle;
  if (openGraphDescription) openGraphDescription.content = dictionary.metaDescription;
  if (openGraphLocale) openGraphLocale.content = selectedLanguage === "ar" ? "ar_SA" : "en_US";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) element.setAttribute("alt", dictionary[key]);
  });

  languageButtons.forEach((button) => {
    const isSelected = button.dataset.language === selectedLanguage;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });

  setMenu(false);
  if (persist) storeLanguage(selectedLanguage);
}

if (currentYear) {
  currentYear.textContent = new Date().getFullYear();
}

if (menuToggle && headerPanel) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    setMenu(!isOpen);
  });

  headerPanel.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => setMenu(false));
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
      setMenu(false);
      menuToggle.focus();
    }
  });

  document.addEventListener("pointerdown", (event) => {
    const header = document.querySelector("[data-site-header]");
    if (header && !header.contains(event.target)) setMenu(false);
  });

  const desktopQuery = window.matchMedia("(min-width: 48.01rem)");
  desktopQuery.addEventListener("change", (event) => {
    if (event.matches) setMenu(false);
  });
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language));
});

applyLanguage(storedLanguage(), false);
